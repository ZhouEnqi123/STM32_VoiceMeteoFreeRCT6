#include <stdio.h>
#include <stdarg.h>
#include "esp8266.h"

volatile uint32_t uart2_error_code = 0;

/**
 * @brief 调试打印函数（通过 UART1 输出）
 * 功能：类似 printf，将格式化字符串发送到 UART1（调试控制台）
 * 
 * @param format 格式字符串（支持 %d, %s, %x 等）
 * @param ...   可变参数
 */
void DebugPrintf(const char *format, ...)
{
    static char debug_buffer[256];
    va_list args;
    int len;
    
    if (format == NULL) {
        return;
    }
    
    // 格式化字符串
    va_start(args, format);
    len = vsnprintf(debug_buffer, sizeof(debug_buffer) - 1, format, args);
    va_end(args);
    
    if (len < 0) {
        len = 0;
    } else if (len > sizeof(debug_buffer) - 1) {
        len = sizeof(debug_buffer) - 1;
    }
    
    // 发送到 UART1（非阻塞，超时1秒）
    HAL_UART_Transmit(&huart1, (uint8_t *)debug_buffer, len, 100);
}

/**
 * @brief UART2 接收中断回调
 * 此函数在 UART2 接收中断时被调用
 * 用于处理来自 ESP8266 的数据
 * 
 * 工作流程：
 * 1. 接收 UART2 的一个字节
 * 2. 将其存储到 g_uart2_rx_buffer
 * 3. 转发到 UART1（调试输出）
 * 4. 重新启动接收中断以接收下一个字节
 */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) {
        uart2_error_code = huart->ErrorCode;
        if (huart->ErrorCode & HAL_UART_ERROR_ORE) {
            __HAL_UART_CLEAR_OREFLAG(huart);
        }
        HAL_UART_DMAStop(&huart2);
    }
}

